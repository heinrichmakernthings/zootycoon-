// Turns the animal design pack (pack/data/*.json) into js/pack-data.js, which the game loads.
// The pack is the source of truth for species and the 300-entry build catalogue: edit the JSON
// there, then run `npm run pack`. `npm test` fails if js/pack-data.js is out of date.
// Only the fields the game uses are copied, in a compact shape. Emoji stand-ins are added here
// because the pack has no runtime sprites yet (see pack/docs/ART-DIRECTION-AND-ASSET-STATUS.md).
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const read = (f) => JSON.parse(fs.readFileSync(path.join(root, 'pack/data', f), 'utf8'));

const EMOJI = {
  capybara: '🦫',
  'red-panda': '🦊',
  'asian-small-clawed-otter': '🦦',
  'african-penguin': '🐧',
  meerkat: '🐿️',
  'fennec-fox': '🦊',
  rabbit: '🐰',
  'pygmy-goat': '🐐',
  alpaca: '🦙',
  'aldabra-giant-tortoise': '🐢',
  'chilean-flamingo': '🦩',
  'indian-peafowl': '🦚',
  'ring-tailed-lemur': '🐒',
  'two-toed-sloth': '🦥',
  'malayan-tapir': '🐗',
  'african-elephant': '🐘',
  giraffe: '🦒',
  'plains-zebra': '🦓',
  'arctic-fox': '🐺',
  'snow-leopard': '🐆',
};
const TEMPLATE_EMOJI = {
  shelter: '🛖',
  feeder: '🥕',
  water: '💧',
  'keeper-gate': '🚪',
  privacy: '🌿',
  rest: '🪵',
  nursery: '🧺',
  terrain: '🟫',
  viewing: '🪟',
  sign: '🪧',
  border: '🌷',
  shade: '⛱️',
};
const BEHAVIOUR_EMOJI = {
  swim: '🫧',
  soak: '🛁',
  dive: '🫧',
  wade: '🫧',
  wallow: '🟤',
  climb: '🪜',
  climb_slow: '🪜',
  graze: '🌾',
  browse: '🌿',
};

const species = read('species.json').map((s) => ({
  id: s.id,
  name: s.display_name,
  example: s.example_name,
  emoji: EMOJI[s.id] || '🐾',
  zone: s.zone,
  stage: s.unlock_stage,
  personality: s.personality,
  signature: s.signature_behaviour,
  adult: s.appearance.adult,
  baby: s.appearance.baby,
  habitat: s.habitat.name,
  footprint: s.habitat.suggested_footprint_tiles,
  tilesPerSlot: s.habitat.tiles_per_resident_slot,
  group: s.habitat.initial_group_range,
  need: s.habitat.priority_need,
  needLabel: s.habitat.action_label,
  egg: s.life_cycle.egg_phase,
  days: {
    pre: s.life_cycle.prebirth_game_days,
    baby: s.life_cycle.baby_game_days,
    juvenile: s.life_cycle.juvenile_game_days,
    cooldown: s.life_cycle.breeding_cooldown_game_days,
  },
  follow: s.life_cycle.family_follow,
  wellbeingMin: s.life_cycle.minimum_wellbeing,
  nursery: s.life_cycle.requires_nursery,
  upkeepMult: {
    baby: s.life_cycle.baby_daily_upkeep_multiplier,
    juvenile: s.life_cycle.juvenile_daily_upkeep_multiplier,
    adult: s.life_cycle.adult_daily_upkeep_multiplier,
  },
  buy: s.economy.adult_buy_price_coins,
  sale: s.economy.adult_base_sale_price_coins,
  saleMax: s.economy.sale_price_max_multiplier_of_buy,
  upkeep: s.economy.daily_upkeep_coins,
  quest: s.quest,
  concept: s.art.concept_path,
}));

const items = read('items.json').map((i) => ({
  id: i.id,
  sp: i.species_id,
  name: i.name,
  cat: i.category,
  price: i.price_coins,
  fp: i.footprint_tiles,
  place: i.placement,
  effect: i.effect.type,
  value: i.effect.value,
  behaviour: i.behaviour,
  template: i.source_template,
  level: i.upgrade_level,
  emoji: TEMPLATE_EMOJI[i.source_template] || BEHAVIOUR_EMOJI[i.behaviour] || '✨',
}));

const systems = read('systems.json');
const out =
  '// GENERATED by tools/pack.js from pack/data/*.json. Do not edit: change the pack and run `npm run pack`.\n' +
  '(function (root) {\n' +
  `  const PACK = ${JSON.stringify({ species, items, systems })};\n` +
  "  if (typeof module !== 'undefined' && module.exports) module.exports = PACK;\n" +
  '  root.ZooPack = PACK;\n' +
  "})(typeof globalThis !== 'undefined' ? globalThis : this);\n";

const file = path.join(root, 'js/pack-data.js');
if (process.argv.includes('--check')) {
  const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === out;
  console.log(same ? 'js/pack-data.js is up to date.' : 'js/pack-data.js is out of date: run `npm run pack`.');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(file, out);
console.log(`js/pack-data.js: ${species.length} species, ${items.length} catalogue entries.`);
